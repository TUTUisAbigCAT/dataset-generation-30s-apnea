"""Compare whole-night generations of several models on the same participants.

Inputs are output folders of scripts/generate_all_nights.py, e.g. the 2-minute
model and the 30-second + respiratory-event model. Every metric uses the same
positions for every model: samples generated by all models whose real IBI is
observed (> 0). The first --run is the baseline of the paired tests.

Metrics (per model):
  pooled          W1 (ms), KS, mean bias, SD ratio over all participants together
  per participant W1/KS/bias/SD ratio; paired against the baseline: median change,
                  participants improved, Wilcoxon signed-rank p
  per epoch       W1 inside each 30-s epoch (median, p90), share of epochs improved
  stage           pooled W1 and mean IBI for W, Light, REM, Deep
  events          pooled W1 in epochs with / without a respiratory event, and the
                  per-participant event effect (mean IBI in event samples minus
                  non-event samples) of real vs generated
  spectrum        whole-night Welch PSD (10-min segments, values outside 0.3-2.0 s
                  linearly filled in real and generated alike); VLF/LF/HF power,
                  generated minus real in dB
  seams           |level change| across window boundaries (2-s means) vs the real change there
  counterfactual  event models: change caused by the event channel (same noise)

Outputs: summary.json, per_subject.csv, report.md and figures in --output-dir.

Example:
  python scripts/compare_night_generations.py --run 2min=OUT_2MIN --run 30s_apnea=OUT_30S \
      --apnea-label-dir .../DREAMT_PIBI_SE_APNEA --output-dir COMPARE
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np

import apnea_labels as al
from distribution_metrics import ks_statistic, wasserstein1

FS = 25
EPOCH = 750
STAGES = ("W", "Light", "REM", "Deep")
BANDS = dict(VLF=(0.0033, 0.04), LF=(0.04, 0.15), HF=(0.15, 0.4))
REAL_COLOR = "#52514e"
RUN_COLORS = ("#2a78d6", "#eb6834", "#1baf7a")      # validated categorical slots 1-3 (all pairs)


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run", action="append", required=True, metavar="NAME=DIR",
                        help="Model name and generate_all_nights.py output folder; first is the baseline")
    parser.add_argument("--apnea-label-dir", type=Path, default=None,
                        help="Sidecar folder for event strata (default: apnea_samples stored by an event model)")
    parser.add_argument("--event-columns", nargs="+", default=list(al.EVENT_COLUMNS))
    parser.add_argument("--subjects", nargs="*", default=None)
    parser.add_argument("--min-event-samples", type=int, default=750,
                        help="Observed event samples needed for a participant's event effect")
    parser.add_argument("--kde-samples", type=int, default=400000)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--no-figures", action="store_true")
    cli = parser.parse_args(argv)
    runs = []
    for item in cli.run:
        name, separator, folder = item.partition("=")
        if not separator or not name or not folder:
            parser.error("--run expects NAME=DIR")
        runs.append((name, Path(folder).expanduser().resolve()))
    if len(runs) < 2 or len({name for name, _ in runs}) != len(runs):
        parser.error("Give at least two --run entries with distinct names")
    if len(runs) > len(RUN_COLORS):
        parser.error(f"At most {len(RUN_COLORS)} runs can be compared in one report")
    unknown = set(cli.event_columns) - set(al.EVENT_COLUMNS)
    if unknown:
        parser.error(f"Unknown event columns {sorted(unknown)}")
    cli.runs = runs
    return cli


def load_subject(folder, sid):
    with np.load(Path(folder) / "subjects" / f"{sid}.npz", allow_pickle=False) as saved:
        return {key: saved[key] for key in saved.files}


def completed_subjects(folder):
    names = set()
    for meta in (Path(folder) / "subjects").glob("*.json"):
        try:
            value = json.loads(meta.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if value.get("status") == "completed" and (Path(folder) / "subjects" / f"{meta.stem}.npz").is_file():
            names.add(meta.stem)
    return names


def sidecar_events(label_dir, sid, columns, samples):
    path = Path(label_dir) / f"{sid}.npz"
    if not path.is_file():
        return None
    with np.load(path, allow_pickle=False) as saved:
        stored = [str(value) for value in saved["event_columns"]]
        flags = np.asarray(saved["event_flags"])
    combined = flags[:, [stored.index(column) for column in columns]].max(axis=1)
    if combined.size < samples:
        raise ValueError(f"{path.name}: sidecar shorter than the generated night")
    return combined[:samples].astype(bool)


def fill_drops(values, low=0.3, high=2.0):
    """Linear fill of missing markers and out-of-range values (identical rule for real and generated)."""
    values = np.asarray(values, dtype=np.float64).copy()
    good = np.isfinite(values) & (values >= low) & (values < high)
    if good.sum() < 2:
        return None
    index = np.arange(values.size)
    values[~good] = np.interp(index[~good], index[good], values[good])
    return values


def welch_psd(values):
    from scipy.signal import welch
    nperseg = min(15000, values.size)
    return welch(values - values.mean(), fs=FS, window="hann", nperseg=nperseg, noverlap=nperseg // 2,
                 detrend="constant", scaling="density")


def band_power(frequency, psd, band):
    low, high = band
    selected = (frequency >= low) & (frequency < high)
    if selected.sum() < 2:
        return None
    return float(np.trapezoid(psd[selected], frequency[selected]) if hasattr(np, "trapezoid")
                 else np.trapz(psd[selected], frequency[selected]))


def epoch_w1(reference, generated, observed):
    """W1 (ms) inside each 30-s epoch with >= 2 observed samples; NaN otherwise."""
    epochs = reference.size // EPOCH
    out = np.full(epochs, np.nan)
    r = reference[:epochs * EPOCH].reshape(epochs, EPOCH)
    g = generated[:epochs * EPOCH].reshape(epochs, EPOCH)
    m = observed[:epochs * EPOCH].reshape(epochs, EPOCH)
    for e in np.flatnonzero(m.sum(axis=1) >= 2):
        out[e] = np.mean(np.abs(np.sort(r[e][m[e]]) - np.sort(g[e][m[e]]))) * 1000.0
    return out


def seam_steps(reference, generated, observed, window_id, span=50):
    """[boundaries, 2] |level change| across each window boundary: generated, real (same positions).

    Level = mean of the observed samples in the 2 s before / after the boundary,
    because real IBI is often missing (0) right at a 30-s epoch edge.
    """
    window_id = np.asarray(window_id)
    boundary = np.flatnonzero(np.diff(window_id) != 0) + 1
    boundary = boundary[(window_id[boundary] >= 0) & (window_id[boundary - 1] >= 0)]
    rows = []
    for b in boundary:
        left, right = slice(max(0, b - span), b), slice(b, min(len(reference), b + span))
        lm, rm = observed[left], observed[right]
        if lm.any() and rm.any():
            rows.append((abs(generated[left][lm].mean() - generated[right][rm].mean()),
                         abs(reference[left][lm].mean() - reference[right][rm].mean())))
    return np.asarray(rows, dtype=np.float64).reshape(-1, 2)


def distribution(real, generated):
    real_std = float(real.std())
    return dict(samples=int(real.size), w1_ms=wasserstein1(real, generated) * 1000.0,
                ks=ks_statistic(real, generated), real_mean_s=float(real.mean()),
                generated_mean_s=float(generated.mean()),
                mean_bias_ms=float(generated.mean() - real.mean()) * 1000.0,
                std_ratio=float(generated.std() / real_std) if real_std > 0 else None)


def paired(baseline, other):
    """other - baseline for matching finite pairs; lower metric = better."""
    baseline, other = np.asarray(baseline, dtype=np.float64), np.asarray(other, dtype=np.float64)
    keep = np.isfinite(baseline) & np.isfinite(other)
    difference = other[keep] - baseline[keep]
    result = dict(pairs=int(keep.sum()), median_change=float(np.median(difference)) if keep.any() else None,
                  mean_change=float(difference.mean()) if keep.any() else None,
                  improved=int((difference < 0).sum()), worse=int((difference > 0).sum()),
                  improved_share=float((difference < 0).mean()) if keep.any() else None, wilcoxon_p=None)
    if keep.sum() >= 5 and np.any(difference != 0):
        from scipy.stats import wilcoxon
        result["wilcoxon_p"] = float(wilcoxon(other[keep], baseline[keep]).pvalue)
    return result


def run(cli):
    output = cli.output_dir.expanduser().resolve()
    output.mkdir(parents=True, exist_ok=True)
    names = [name for name, _ in cli.runs]
    available = [completed_subjects(folder) for _, folder in cli.runs]
    common = sorted(set.intersection(*available))
    if cli.subjects:
        wanted = set(cli.subjects)
        common = [sid for sid in common if sid in wanted]
    if not common:
        raise ValueError("No participant is completed in every run")
    pooled = {name: [] for name in names}
    pooled_real, pooled_stage, pooled_event = [], [], []
    rows, epoch_rows, seam, spectra, effects = [], {n: [] for n in names}, {n: [] for n in names}, [], []
    event_source = None
    for sid in common:
        loaded = [load_subject(folder, sid) for _, folder in cli.runs]
        reference = loaded[0]["reference_ibi_seconds"].astype(np.float64)
        for data in loaded[1:]:
            if data["reference_ibi_seconds"].shape != reference.shape or not np.array_equal(
                    data["reference_ibi_seconds"], loaded[0]["reference_ibi_seconds"]):
                raise ValueError(f"{sid}: runs disagree on the real IBI (different data folders?)")
        samples = reference.size
        covered = np.logical_and.reduce([data["covered"] for data in loaded])
        observed = covered & np.isfinite(reference) & (reference > 0)
        stage = np.repeat(loaded[0]["stage_epochs"].astype(np.int64), EPOCH)
        events = None
        if cli.apnea_label_dir is not None:
            events = sidecar_events(cli.apnea_label_dir, sid, cli.event_columns, samples)
            event_source = "sidecar folder"
        if events is None:
            stored = next((data["apnea_samples"] for data in loaded if "apnea_samples" in data), None)
            if stored is not None:
                events, event_source = stored.astype(bool), event_source or "apnea_samples of an event model"
        epoch_event = None
        if events is not None:
            epoch_event = np.repeat(events[:samples // EPOCH * EPOCH].reshape(-1, EPOCH).any(axis=1), EPOCH)
        pooled_real.append(reference[observed].astype(np.float32))
        pooled_stage.append(stage[observed].astype(np.int8))
        pooled_event.append((epoch_event[observed] if epoch_event is not None
                             else np.full(int(observed.sum()), -1)).astype(np.int8))
        row = dict(subject=sid, epochs=samples // EPOCH, observed_samples=int(observed.sum()),
                   event_sample_fraction=float(events.mean()) if events is not None else None)
        real_effect = None
        if events is not None and (observed & events).sum() >= cli.min_event_samples and (observed & ~events).sum() >= 2:
            real_effect = float(reference[observed & events].mean() - reference[observed & ~events].mean()) * 1000.0
        row["real_event_effect_ms"] = real_effect
        filled_real = fill_drops(np.where(covered, reference, np.nan)) if covered.all() else None
        spectrum = None
        if filled_real is not None and filled_real.size >= 2 * 15000:
            frequency, real_psd = welch_psd(filled_real)
            spectrum = dict(subject=sid, frequency=frequency, real=real_psd)
        for name, data in zip(names, loaded):
            generated = data["generated_ibi_seconds"].astype(np.float64)
            gen_obs = generated[observed]
            pooled[name].append(gen_obs.astype(np.float32))
            if observed.sum() >= 2:
                metrics = distribution(reference[observed], gen_obs)
                row.update({f"{name}_w1_ms": metrics["w1_ms"], f"{name}_ks": metrics["ks"],
                            f"{name}_mean_bias_ms": metrics["mean_bias_ms"], f"{name}_std_ratio": metrics["std_ratio"]})
            per_epoch = epoch_w1(reference, np.where(covered, generated, 0.0), observed)
            epoch_rows[name].append(per_epoch)
            row[f"{name}_epoch_w1_median_ms"] = float(np.nanmedian(per_epoch)) if np.isfinite(per_epoch).any() else None
            if real_effect is not None:
                row[f"{name}_event_effect_ms"] = float(generated[observed & events].mean()
                                                       - generated[observed & ~events].mean()) * 1000.0
            steps = seam_steps(reference, generated, observed, data["window_id"])
            if steps.size:
                seam[name].append(steps)
            if spectrum is not None:
                filled = fill_drops(generated)
                if filled is not None:
                    spectrum[name] = welch_psd(filled)[1]
            effect_path = Path(dict(cli.runs)[name]) / "subjects" / f"{sid}_apnea_effect.npz"
            if effect_path.is_file():
                with np.load(effect_path) as saved:
                    change = saved["generated_with_events"].astype(np.float64) - saved["generated_events_zeroed"]
                    event = saved["event"]
                effects.append(dict(run=name, subject=sid,
                                    event_ms=float(change[event].mean() * 1000.0) if event.any() else None,
                                    non_event_ms=float(change[~event].mean() * 1000.0) if (~event).any() else None))
        if spectrum is not None and all(name in spectrum for name in names):
            spectra.append(spectrum)
        rows.append(row)

    real_all = np.concatenate(pooled_real).astype(np.float64)
    stage_all = np.concatenate(pooled_stage)
    event_all = np.concatenate(pooled_event)
    summary = dict(schema="dreamt_night_generation_comparison_v1", runs={n: str(f) for n, f in cli.runs},
                   baseline=names[0], subjects=len(common), subject_ids=common,
                   positions="generated by every model and real IBI observed (> 0)",
                   event_strata_source=event_source, event_columns=cli.event_columns, models={})
    baseline_name = names[0]
    for index, name in enumerate(names):
        generated_all = np.concatenate(pooled[name]).astype(np.float64)
        model = dict(pooled=distribution(real_all, generated_all), stages={}, events={})
        for code, stage_name in enumerate(STAGES):
            selected = stage_all == code
            if selected.sum() >= 2:
                model["stages"][stage_name] = distribution(real_all[selected], generated_all[selected])
        for flag, label in ((1, "event_epochs"), (0, "no_event_epochs")):
            selected = event_all == flag
            if selected.sum() >= 2:
                model["events"][label] = distribution(real_all[selected], generated_all[selected])
        per_epoch = np.concatenate(epoch_rows[name])
        finite = per_epoch[np.isfinite(per_epoch)]
        model["per_epoch_w1_ms"] = dict(epochs=int(finite.size), median=float(np.median(finite)),
                                        p90=float(np.quantile(finite, .9)), mean=float(finite.mean()))
        if seam[name]:
            steps = np.concatenate(seam[name])
            model["seams"] = dict(boundaries=int(len(steps)), generated_mean_step_ms=float(steps[:, 0].mean() * 1000),
                                  real_mean_step_ms_same_positions=float(steps[:, 1].mean() * 1000))
        effect_pairs = [(r["real_event_effect_ms"], r.get(f"{name}_event_effect_ms")) for r in rows
                        if r["real_event_effect_ms"] is not None and r.get(f"{name}_event_effect_ms") is not None]
        if effect_pairs:
            values = np.asarray(effect_pairs)
            model["event_effect"] = dict(
                subjects=len(values), real_mean_ms=float(values[:, 0].mean()), generated_mean_ms=float(values[:, 1].mean()),
                mean_abs_error_ms=float(np.abs(values[:, 1] - values[:, 0]).mean()),
                pearson_r=(float(np.corrcoef(values[:, 0], values[:, 1])[0, 1])
                           if len(values) >= 3 and values[:, 0].std() > 0 and values[:, 1].std() > 0 else None))
        run_effects = [e for e in effects if e["run"] == name and e["event_ms"] is not None]
        if run_effects:
            model["counterfactual_event_channel"] = dict(
                subjects=len(run_effects),
                mean_change_event_samples_ms=float(np.mean([e["event_ms"] for e in run_effects])),
                mean_change_non_event_samples_ms=float(np.nanmean([np.nan if e["non_event_ms"] is None
                                                                   else e["non_event_ms"] for e in run_effects])),
                definition="generated(event channel as recorded) - generated(event channel 0), same noise")
        if spectra:
            bands = {}
            for band, limits in BANDS.items():
                differences = []
                for spectrum in spectra:
                    real_power = band_power(spectrum["frequency"], spectrum["real"], limits)
                    gen_power = band_power(spectrum["frequency"], spectrum[name], limits)
                    if real_power and gen_power and real_power > 0 and gen_power > 0:
                        differences.append(10 * np.log10(gen_power / real_power))
                if differences:
                    bands[band] = dict(subjects=len(differences), mean_db=float(np.mean(differences)),
                                       median_db=float(np.median(differences)),
                                       mean_abs_db=float(np.mean(np.abs(differences))))
            model["spectrum_generated_minus_real"] = bands
        if index:
            model["paired_vs_baseline"] = dict(
                subject_w1_ms=paired([r.get(f"{baseline_name}_w1_ms", np.nan) for r in rows],
                                     [r.get(f"{name}_w1_ms", np.nan) for r in rows]),
                subject_ks=paired([r.get(f"{baseline_name}_ks", np.nan) for r in rows],
                                  [r.get(f"{name}_ks", np.nan) for r in rows]),
                subject_abs_mean_bias_ms=paired([abs(r.get(f"{baseline_name}_mean_bias_ms", np.nan)) for r in rows],
                                                [abs(r.get(f"{name}_mean_bias_ms", np.nan)) for r in rows]),
                epoch_w1_ms=paired(np.concatenate(epoch_rows[baseline_name]), per_epoch))
        summary["models"][name] = model
    (output / "summary.json").write_text(json.dumps(summary, indent=2, allow_nan=False), encoding="utf-8")
    fields = list(dict.fromkeys(key for row in rows for key in row))
    with (output / "per_subject.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    write_report(output / "report.md", summary)
    if not cli.no_figures:
        figures(output, names, real_all, pooled, rows, spectra, summary, cli.kde_samples)
    print(json.dumps({name: dict(pooled_w1_ms=round(model["pooled"]["w1_ms"], 2),
                                 epoch_w1_median_ms=round(model["per_epoch_w1_ms"]["median"], 2))
                      for name, model in summary["models"].items()}), flush=True)
    return summary


def _fmt(value, digits=1):
    if value is None:
        return "-"
    if isinstance(value, (int, np.integer)):
        return str(value)
    return f"{value:.{digits}f}"


def write_report(path, summary):
    names = list(summary["models"])
    lines = [f"# Whole-night comparison ({summary['subjects']} participants)", "",
             f"Baseline: **{summary['baseline']}**. Positions: {summary['positions']}.", "",
             "| metric | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]

    def add(label, getter, digits=1):
        values = []
        for name in names:
            try:
                values.append(_fmt(getter(summary["models"][name]), digits))
            except (KeyError, TypeError):
                values.append("-")
        lines.append(f"| {label} | " + " | ".join(values) + " |")

    add("pooled W1 (ms)", lambda m: m["pooled"]["w1_ms"])
    add("pooled KS", lambda m: m["pooled"]["ks"], 3)
    add("mean bias (ms)", lambda m: m["pooled"]["mean_bias_ms"])
    add("SD ratio gen/real", lambda m: m["pooled"]["std_ratio"], 2)
    add("per-epoch W1 median (ms)", lambda m: m["per_epoch_w1_ms"]["median"])
    add("per-epoch W1 p90 (ms)", lambda m: m["per_epoch_w1_ms"]["p90"])
    for stage in STAGES:
        add(f"W1 {stage} (ms)", lambda m, s=stage: m["stages"][s]["w1_ms"])
    add("W1 event epochs (ms)", lambda m: m["events"]["event_epochs"]["w1_ms"])
    add("W1 no-event epochs (ms)", lambda m: m["events"]["no_event_epochs"]["w1_ms"])
    add("event effect real (ms)", lambda m: m["event_effect"]["real_mean_ms"])
    add("event effect generated (ms)", lambda m: m["event_effect"]["generated_mean_ms"])
    add("event effect r (participants)", lambda m: m["event_effect"]["pearson_r"], 2)
    add("event channel counterfactual (ms)", lambda m: m["counterfactual_event_channel"]["mean_change_event_samples_ms"])
    for band in BANDS:
        add(f"{band} gen - real (dB)", lambda m, b=band: m["spectrum_generated_minus_real"][b]["mean_db"], 2)
    add("seam step generated (ms)", lambda m: m["seams"]["generated_mean_step_ms"])
    add("seam step real same places (ms)", lambda m: m["seams"]["real_mean_step_ms_same_positions"])
    add("participants with lower W1", lambda m: m["paired_vs_baseline"]["subject_w1_ms"]["improved"], 0)
    add("Wilcoxon p (participant W1)", lambda m: m["paired_vs_baseline"]["subject_w1_ms"]["wilcoxon_p"], 4)
    add("share of epochs with lower W1", lambda m: m["paired_vs_baseline"]["epoch_w1_ms"]["improved_share"], 3)
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def figures(output, names, real_all, pooled, rows, spectra, summary, kde_samples):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from scipy.stats import gaussian_kde

    plt.rcParams.update({"axes.spines.top": False, "axes.spines.right": False, "axes.grid": True,
                         "grid.color": "#e4e3df", "grid.linewidth": 0.6, "axes.edgecolor": "#8a8985",
                         "font.size": 10})
    rng = np.random.default_rng(0)
    pick = rng.choice(real_all.size, size=min(kde_samples, real_all.size), replace=False)
    grid = np.linspace(0.0, 2.0, 600)
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.plot(grid, gaussian_kde(real_all[pick], bw_method=0.03)(grid), color=REAL_COLOR, lw=2, label="real")
    for color, name in zip(RUN_COLORS, names):
        values = np.concatenate(pooled[name]).astype(np.float64)[pick]
        ax.plot(grid, gaussian_kde(values, bw_method=0.03)(grid), color=color, lw=2,
                label=f"{name} (W1 {summary['models'][name]['pooled']['w1_ms']:.0f} ms)")
    ax.set_xlabel("IBI (s)")
    ax.set_ylabel("density")
    ax.set_title(f"IBI distribution, all participants ({summary['subjects']})")
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(output / "distribution_all.png", dpi=160)
    plt.close(fig)

    baseline = names[0]
    for color, name in zip(RUN_COLORS[1:], names[1:]):
        x = np.array([r.get(f"{baseline}_w1_ms", np.nan) for r in rows], dtype=float)
        y = np.array([r.get(f"{name}_w1_ms", np.nan) for r in rows], dtype=float)
        keep = np.isfinite(x) & np.isfinite(y)
        if not keep.any():
            continue
        fig, ax = plt.subplots(figsize=(5, 5))
        limit = float(max(x[keep].max(), y[keep].max())) * 1.05
        ax.plot([0, limit], [0, limit], color="#8a8985", lw=1, ls="--")
        ax.scatter(x[keep], y[keep], s=40, color=color, edgecolor="white", linewidth=1.5, zorder=3)
        below = int((y[keep] < x[keep]).sum())
        ax.set_xlim(0, limit)
        ax.set_ylim(0, limit)
        ax.set_xlabel(f"{baseline}: W1 per participant (ms)")
        ax.set_ylabel(f"{name}: W1 per participant (ms)")
        ax.set_title(f"Below the line = {name} better ({below} of {int(keep.sum())})")
        fig.tight_layout()
